-- Bulk past-paper ingestion and hybrid semantic retrieval.
-- Apply after the existing migrations. Embeddings are additive; lexical search remains available.
create extension if not exists vector with schema extensions;

alter table public.materials
  add column if not exists archive_path text,
  add column if not exists exam_year integer,
  add column if not exists exam_session text,
  add column if not exists course_code text,
  add column if not exists paper_variant text,
  add column if not exists mime_type text,
  add column if not exists file_size bigint,
  add column if not exists ingestion_status text not null default 'ready',
  add column if not exists ingestion_error text,
  add column if not exists metadata_confidence numeric(4,3);

alter table public.materials
  drop constraint if exists materials_ingestion_status_check;
alter table public.materials
  add constraint materials_ingestion_status_check
  check (ingestion_status in ('queued','extracting','indexing','embedding','ready','failed'));

create index if not exists materials_past_paper_filters_idx
  on public.materials (type, exam_year, exam_session, course_code, ingestion_status);
create unique index if not exists materials_archive_path_unique
  on public.materials (archive_path)
  where archive_path is not null;

alter table public.ai_documents
  add column if not exists embedding_model text,
  add column if not exists ingestion_status text not null default 'ready',
  add column if not exists ingestion_error text;

alter table public.ai_chunks
  add column if not exists embedding vector(1536),
  add column if not exists embedding_model text;

create index if not exists ai_chunks_embedding_hnsw_idx
  on public.ai_chunks using hnsw (embedding vector_cosine_ops)
  where embedding is not null;

drop function if exists public.ai_vector_search(vector, text, int, text[], int, text, text);
create or replace function public.ai_vector_search(
  query_embedding vector(1536),
  p_scope text default 'any',
  p_limit int default 12,
  p_material_ids text[] default null,
  p_exam_year int default null,
  p_exam_session text default null,
  p_course_code text default null,
  p_document_ids uuid[] default null
)
returns table (
  chunk_id bigint,
  document_id uuid,
  material_id text,
  title text,
  citation text,
  idx int,
  content text,
  similarity real
)
language sql stable security invoker as $$
  select c.id, c.document_id, d.material_id::text, d.title, d.citation,
         c.idx, c.content, (1 - (c.embedding <=> query_embedding))::real
  from public.ai_chunks c
  join public.ai_documents d on d.id = c.document_id
  left join public.materials m on m.id = d.material_id::text
  where c.embedding is not null
    and (p_scope = 'any' or c.scope = p_scope)
    and (p_document_ids is null or c.document_id = any(p_document_ids))
    and (p_material_ids is null or d.material_id::text = any(p_material_ids))
    and (p_exam_year is null or m.exam_year = p_exam_year)
    and (p_exam_session is null or m.exam_session = p_exam_session)
    and (p_course_code is null or m.course_code = p_course_code)
  order by c.embedding <=> query_embedding
  limit greatest(1, least(coalesce(p_limit, 12), 50));
$$;

grant execute on function public.ai_vector_search(vector(1536), text, int, text[], int, text, text, uuid[]) to authenticated;
comment on column public.materials.archive_path is 'Original relative path in a bulk archive; used for idempotent ingestion and auditability.';
comment on column public.ai_chunks.embedding is 'Embedding generated by the configured ingestion model; tsv remains the exact-match fallback.';
